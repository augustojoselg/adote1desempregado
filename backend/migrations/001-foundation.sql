CREATE TABLE users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('Mentor','Profissional','Empresa')),
  bio TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '', linkedin TEXT NOT NULL DEFAULT '',
  token_hash TEXT NOT NULL,
  consent_given INTEGER NOT NULL DEFAULT 0 CHECK(consent_given IN (0,1)),
  consent_at TIMESTAMPTZ, privacy_policy_version TEXT,
  anonymized_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  session_expires_at TIMESTAMPTZ
);
CREATE INDEX idx_users_token ON users(token_hash) WHERE token_hash <> '';
CREATE TABLE elos (
  id TEXT PRIMARY KEY,
  mentor_id TEXT NOT NULL REFERENCES users(id),
  professional_id TEXT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'Combinado' CHECK(status IN ('Combinado','Em contato','Entrevistas','Recolocado')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(mentor_id, professional_id)
);
CREATE TABLE jobs (
  id TEXT PRIMARY KEY, company TEXT NOT NULL, title TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT '', link TEXT NOT NULL,
  posted_by TEXT NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE consent_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  action TEXT NOT NULL CHECK(action IN ('given','revoked','export_requested','deletion_requested')),
  policy_version TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_elos_mentor ON elos(mentor_id);
CREATE INDEX idx_elos_professional ON elos(professional_id);
CREATE INDEX idx_jobs_posted_by ON jobs(posted_by);
