import { test, after } from 'node:test';
import assert from 'node:assert/strict';
process.env.NODE_ENV = 'test';
process.env.FRONTEND_ORIGIN = 'https://empregosocial.example';
process.env.PGSCHEMA = 'test_' + (await import('node:crypto')).randomUUID().replaceAll('-', '');
const { db } = await import('../src/db.js');
process.env.NODE_ENV = 'production';
const { default: app } = await import('../src/server.js');
await db.exec(`CREATE SCHEMA ${process.env.PGSCHEMA}`);
const { migrate } = await import('../src/migrate.js');
await migrate();
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
after(async () => { server.close(); await db.exec(`DROP SCHEMA ${process.env.PGSCHEMA} CASCADE`); await db.close(); });
const base = `http://127.0.0.1:${server.address().port}/api`;
test('produção: cookie protegido, CSRF e nenhuma credencial de sessão no JSON', async () => {
  const body = JSON.stringify({ name: 'Conta teste', role: 'Profissional', consent: true });
  const post = origin => fetch(base + '/auth/signup', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body });
  assert.equal((await post('https://evil.example')).status, 403);
  const signup = await post(process.env.FRONTEND_ORIGIN);
  assert.equal(signup.status, 201);
  assert.equal(signup.headers.get('cache-control'), 'no-store');
  assert.equal((await signup.json()).token, undefined);
  const setCookie = signup.headers.get('set-cookie');
  assert.match(setCookie, /HttpOnly/);
  assert.match(setCookie, /Secure/);
  assert.match(setCookie, /SameSite=Strict/);
  const cookie = setCookie.split(';')[0];
  const me = await fetch(base + '/auth/me', { headers: { Cookie: cookie } });
  assert.equal(me.status, 200);
  assert.equal(me.headers.get('cache-control'), 'no-store');
  const token = cookie.slice(cookie.indexOf('=') + 1);
  assert.equal((await fetch(base + '/auth/me', { headers: { Authorization: `Bearer ${token}` } })).status, 401);
  assert.equal((await fetch(base + '/auth/logout', { method: 'POST', headers: { Cookie: cookie } })).status, 403);
  assert.equal((await fetch(base + '/auth/logout', { method: 'POST', headers: { Cookie: cookie, Origin: process.env.FRONTEND_ORIGIN } })).status, 204);
  assert.equal((await fetch(base + '/auth/me', { headers: { Cookie: cookie } })).status, 401);
});
